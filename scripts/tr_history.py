"""History over the immutable TR Test Focus runs.

Stage 8 promotes every published run into
``tr_reports/<build label>/runs/<UTC stamp>_<source hash>/`` and never rewrites
one — only ``latest.json`` is overwritten. So the run tree *is* the history and
this module only reads it; nothing here fetches, re-analyses, or writes.

Three things it deliberately does not claim:

* **A missing day is not a failure.** A run is published only when the evidence,
  the model, or the analysis schema changed; an ``unchanged`` outcome writes
  status.json and no run at all. A quiet day and a day the pipeline never ran
  look identical here, so the view must not present gaps as incidents.
* **Only the newest attempt has a status.** ``status.json`` holds the latest
  attempt for the product and is overwritten too, so a failed fetch leaves
  nothing behind. This is the history of what was *published*, not what was
  tried.
* **A bug-count change means something only within one Close Build.** Two runs
  of different builds are two different cohorts, not growth, so the delta is
  computed only against the previous run of the *same* build.

Past runs are *reported*, not re-verified: ``audit_report_manifest`` checks the
hashes of the run latest.json points at, and this view makes no such claim about
the ones behind it. It says where each fact came from instead, in
``provenance``.

Run time is taken from the directory stamp (UTC) or the manifest's
``generated_at`` (UTC ISO) — never from the report header's date, which
``summarize_tr_bugs`` writes with a bare ``datetime.now()`` in the Mac Mini's
local time and no offset.
"""
import json
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path

try:
    from .tr_focus_view import build_focus_list, focus_list_markdown
except ImportError:
    from tr_focus_view import build_focus_list, focus_list_markdown

DEFAULT_HISTORY_DAYS = 10

# <UTC stamp>_<first 8 of the evidence source hash>, as stage 8 names run dirs.
RUN_NAME_RE = re.compile(r"^(?P<stamp>\d{8}T\d{6}\d{0,6})Z_(?P<source>[0-9a-f]{6,64})$")
_REPORT_HEADER_RE = re.compile(
    r"^<!--\s*Generated by summarize_tr_bugs\.py(?P<body>.*?)-->"
)
_RUN_FILES = {
    "focus_list": "focus_list.md",
    "report": "test_focus_summary.md",
    "analysis": "analysis.json",
    "details": "bug_details.json",
}


def parse_run_stamp(run_id: str) -> datetime | None:
    """UTC time encoded in a run directory name, or None if it is not one."""
    match = RUN_NAME_RE.match(str(run_id or ""))
    if not match:
        return None
    stamp = match.group("stamp")
    for fmt in ("%Y%m%dT%H%M%S%f", "%Y%m%dT%H%M%S"):
        try:
            return datetime.strptime(stamp, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def _parse_iso(value: object) -> datetime | None:
    try:
        parsed = datetime.fromisoformat(str(value or "").replace("Z", "+00:00"))
    except (TypeError, ValueError):
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def read_report_header(path: Path) -> dict:
    """Read the provenance comment ``summarize_tr_bugs`` writes as line 1.

    Cheap enough to run over every historical run — it reads one line, not the
    300 KB report — and it is the only per-run record of the model and the true
    Close Build for runs published before manifest.json existed. Its date is
    *not* read: it is local-time and unmarked, while the directory stamp is UTC.
    """
    try:
        with path.open(encoding="utf-8") as handle:
            first = handle.readline()
    except OSError:
        return {}
    match = _REPORT_HEADER_RE.match(first.strip())
    if not match:
        return {}
    fields = {}
    for part in match.group("body").split("|"):
        key, _, value = part.partition("=")
        key = key.strip().casefold()
        if _ and key:
            fields[key] = value.strip()
    header = {}
    if fields.get("model"):
        header["model"] = fields["model"]
    if fields.get("close_build"):
        header["close_build"] = fields["close_build"]
    for key, target in (("bugs", "bug_count"), ("schema", "schema_version")):
        try:
            header[target] = int(fields[key])
        except (KeyError, TypeError, ValueError):
            continue
    return header


def read_run_manifest(run_dir: Path) -> dict:
    """The run's own copy of the manifest latest.json also received.

    Stage 8 started writing it into the run directory later than the runs
    themselves, so older runs legitimately have none; they fall back to the
    report header.
    """
    try:
        manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return manifest if isinstance(manifest, dict) else {}


def read_run_record(run_dir: Path) -> dict | None:
    """Describe one published run from its directory alone.

    Precedence is exactness, not convenience: the run's own manifest, then the
    report header, then the directory name. ``provenance`` says which answered,
    so a view can avoid presenting a reconstructed row as a recorded one.
    """
    run_at = parse_run_stamp(run_dir.name)
    if run_at is None or not run_dir.is_dir():
        return None
    artifacts = {
        key: (run_dir / name) if (run_dir / name).is_file() else None
        for key, name in _RUN_FILES.items()
    }
    if not any(artifacts.values()):
        return None

    manifest = read_run_manifest(run_dir)
    header = read_report_header(artifacts["report"]) if artifacts["report"] else {}
    # The directory is a *sanitized* build label ("0916_25.0.7_365_Ultra_…"),
    # so it is the last resort for the build, never the first.
    build_label = run_dir.parent.parent.name
    bug_codes = [str(code) for code in (manifest.get("bug_codes") or [])]
    bug_count = manifest.get("bug_count_total") or manifest.get("bug_count")
    if bug_count is None:
        bug_count = header.get("bug_count")
    provenance = (
        "manifest" if manifest else "report header" if header else "directory"
    )
    return {
        "run_id": run_dir.name,
        "run_dir": run_dir,
        "run_at": _parse_iso(manifest.get("generated_at")) or run_at,
        "close_build": str(
            manifest.get("close_build") or header.get("close_build") or build_label
        ),
        "build_label": build_label,
        "bug_count": int(bug_count) if bug_count is not None else None,
        "bug_codes": bug_codes,
        "analyzed_count": manifest.get("bug_count_analyzed"),
        "tr_codes": [str(code) for code in (manifest.get("tr_codes") or [])],
        "missing_detail_bug_codes": [
            str(code) for code in (manifest.get("missing_detail_bug_codes") or [])
        ],
        "model": str(manifest.get("model") or header.get("model") or ""),
        "schema_version": manifest.get("analysis_schema_version")
        or header.get("schema_version"),
        "source_sha256": str(
            manifest.get("source_sha256")
            or (RUN_NAME_RE.match(run_dir.name).group("source"))
        ),
        "provenance": provenance,
        "artifacts": artifacts,
        "manifest": manifest,
    }


def current_run_dir(product_dir: Path, manifest: dict) -> Path | None:
    """The run directory ``latest.json`` currently points at."""
    for key in ("focus_list_path", "report_path", "analysis_path", "details_path"):
        value = manifest.get(key)
        if not value:
            continue
        candidate = Path(str(value))
        if not candidate.is_absolute():
            candidate = Path(product_dir) / candidate
        try:
            candidate = candidate.resolve()
            candidate.relative_to(Path(product_dir).resolve())
        except (OSError, ValueError):
            continue
        return candidate.parent
    return None


def run_history(
    product_dir: Path,
    *,
    days: int = DEFAULT_HISTORY_DAYS,
    now: datetime | None = None,
    current_dir: Path | None = None,
) -> list[dict]:
    """Published runs from the last ``days``, newest first.

    ``bug_delta`` compares each run with the previous run of the same Close
    Build, and stays None across a build change: a different build is a
    different cohort, so the difference would not be a change in anything.
    """
    report_root = Path(product_dir) / "tr_reports"
    if not report_root.is_dir():
        return []
    cutoff = (now or datetime.now(timezone.utc)) - timedelta(days=max(int(days), 0))
    records = []
    for run_dir in sorted(report_root.glob("*/runs/*")):
        record = read_run_record(run_dir)
        if record and record["run_at"] >= cutoff:
            records.append(record)
    records.sort(key=lambda row: (row["run_at"], row["run_id"]))

    previous_by_build: dict[str, int] = {}
    for record in records:
        count, build = record["bug_count"], record["close_build"]
        earlier = previous_by_build.get(build)
        record["bug_delta"] = (
            count - earlier if count is not None and earlier is not None else None
        )
        if count is not None:
            previous_by_build[build] = count
        record["is_current"] = bool(
            current_dir and record["run_dir"].resolve() == Path(current_dir).resolve()
        )
    records.reverse()
    return records


def history_digest(records: list[dict], days: int = DEFAULT_HISTORY_DAYS) -> dict:
    """One-line shape of the window: runs, builds, and the days they fell on."""
    builds = list(dict.fromkeys(record["close_build"] for record in records))
    days_seen = {record["run_at"].date() for record in records}
    return {
        "days": days,
        "run_count": len(records),
        "builds": builds,
        "days_with_runs": len(days_seen),
        "first_run_at": records[-1]["run_at"] if records else None,
        "last_run_at": records[0]["run_at"] if records else None,
    }


def run_focus_list(record: dict) -> tuple[str, str]:
    """A past run's focus list, and a note saying where it came from.

    Prefer the file that run wrote, so an archived page and the archived file
    cannot disagree — the same rule the live tab follows. Runs published before
    the focus list existed are rebuilt from that run's own stored evidence,
    which is deterministic, and the note says so rather than passing the
    rebuild off as the artifact.
    """
    stored = (record.get("artifacts") or {}).get("focus_list")
    if stored:
        try:
            text = stored.read_text(encoding="utf-8")
        except OSError:
            text = ""
        if text.strip():
            return text, "The focus list this run published."
    details_fp = (record.get("artifacts") or {}).get("details")
    if not details_fp:
        return "", "This run stored no evidence to rebuild a focus list from."
    try:
        details = json.loads(details_fp.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return "", "This run's stored evidence could not be read."
    analysis_fp = (record.get("artifacts") or {}).get("analysis")
    analysis = {}
    if analysis_fp:
        try:
            analysis = json.loads(analysis_fp.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            analysis = {}
    try:
        markdown = focus_list_markdown(
            build_focus_list(details, analysis),
            record["run_at"].strftime("%Y-%m-%dT%H:%M:%S"),
        )
    except (KeyError, TypeError, ValueError):
        return "", "This run's stored evidence could not be rendered."
    return markdown, (
        "Rebuilt from this run's stored evidence — it predates the saved "
        "focus list."
    )
