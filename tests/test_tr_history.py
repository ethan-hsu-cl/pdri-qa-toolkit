import json
from datetime import datetime, timezone

from scripts.tr_history import (
    current_run_dir, history_digest, parse_run_stamp, read_run_record,
    run_focus_list, run_history,
)

NOW = datetime(2026, 9, 18, 3, 30, tzinfo=timezone.utc)


def write_run(product_dir, build_label, run_id, *, manifest=None, header=None,
              focus_list=None, details=None, analysis=None):
    """Create one run directory the way stage 8 promotes it."""
    run_dir = product_dir / "tr_reports" / build_label / "runs" / run_id
    run_dir.mkdir(parents=True)
    if header is not None:
        (run_dir / "test_focus_summary.md").write_text(header, encoding="utf-8")
    if manifest is not None:
        (run_dir / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    if focus_list is not None:
        (run_dir / "focus_list.md").write_text(focus_list, encoding="utf-8")
    if details is not None:
        (run_dir / "bug_details.json").write_text(json.dumps(details), encoding="utf-8")
    if analysis is not None:
        (run_dir / "analysis.json").write_text(json.dumps(analysis), encoding="utf-8")
    return run_dir


def report_header(close_build, bugs, *, model="qwen3:4b", date="2026-09-17 11:12"):
    return (
        f"<!-- Generated by summarize_tr_bugs.py on {date} | model={model} | "
        f"schema=40 | close_build={close_build} | bugs={bugs} -->\n\n# Report\n"
    )


def manifest_for(close_build, bug_codes, *, generated_at, model="qwen3:4b",
                 run_path=""):
    return {
        "schema_version": 2, "product": "pdri", "close_build": close_build,
        "tr_codes": ["TR260910-067"], "bug_count": len(bug_codes),
        "bug_count_total": len(bug_codes), "bug_count_analyzed": len(bug_codes),
        "bug_codes": bug_codes, "generated_at": generated_at, "model": model,
        "analysis_schema_version": 40,
        "report_path": f"{run_path}/test_focus_summary.md" if run_path else "",
    }


def focus_details():
    return {
        "meta": {"close_build": "16.8.0.189063", "build_trs": [{
            "tr_code": "TR260922-0013", "bugs_loaded": True,
            "bugs_attached_for_verify": [
                {"bug_code": "A-TODO", "is_verified": False, "bug_result": None,
                 "short_description": "not checked", "verify_reason": None},
            ],
        }]},
        "products": {"P": [
            {"BugCode": "B1", "Severity": "2", "ParsedModule": "Timeline",
             "ModuleCategory": "Editor Core", "Resolutions": [{"risk": "none"}]},
        ]},
    }


def test_run_time_comes_from_the_utc_directory_stamp_not_the_local_header_date(tmp_path):
    """The header date is bare local time; the directory stamp is UTC.

    Reading the header's "2026-09-17 11:12" as the run time would place an
    evening UTC run on the wrong side of a day boundary for anyone reading the
    history by date.
    """
    write_run(tmp_path, "16.8.0.189063", "20260917T191058045785Z_5064b828",
              header=report_header("16.8.0.189063", 26, date="2026-09-18 03:10"))
    record = read_run_record(
        tmp_path / "tr_reports/16.8.0.189063/runs/20260917T191058045785Z_5064b828"
    )
    assert record["run_at"] == datetime(2026, 9, 17, 19, 10, 58, 45785, tzinfo=timezone.utc)


def test_a_run_describes_itself_from_its_own_manifest(tmp_path):
    run_path = "tr_reports/16.8.0.189063/runs/20260917T191058045785Z_5064b828"
    write_run(
        tmp_path, "16.8.0.189063", "20260917T191058045785Z_5064b828",
        manifest=manifest_for(
            "16.8.0.189063", ["DRI-1", "DRI-2"],
            generated_at="2026-09-17T19:27:17+00:00", run_path=run_path,
        ),
        header=report_header("16.8.0.189063", 26),
    )
    record = read_run_record(tmp_path / run_path)
    assert record["provenance"] == "manifest"
    assert record["bug_count"] == 2          # the manifest, not the header's 26
    assert record["tr_codes"] == ["TR260910-067"]
    assert record["run_at"].hour == 19 and record["run_at"].minute == 27


def test_a_run_published_before_manifests_falls_back_to_its_report_header(tmp_path):
    """Older runs kept their artifacts but no record of themselves.

    The one-line provenance comment summarize_tr_bugs writes is the only
    per-run source of the model and the true Close Build for those.
    """
    run_path = "tr_reports/16.7.5.188935/runs/20260914T190904776293Z_de7a2c74"
    write_run(tmp_path, "16.7.5.188935", "20260914T190904776293Z_de7a2c74",
              header=report_header("16.7.5.188935", 1))
    record = read_run_record(tmp_path / run_path)
    assert record["provenance"] == "report header"
    assert (record["close_build"], record["bug_count"], record["model"]) == (
        "16.7.5.188935", 1, "qwen3:4b"
    )


def test_the_directory_label_is_the_last_resort_for_the_build(tmp_path):
    """The directory name is a *sanitized* label, so it can differ from eCL's.

    pdr's "0916 25.0.7 365 Ultra Ultimate VL" becomes an underscored label; the
    manifest and the header carry the real string, and only when neither exists
    does the label stand in for it.
    """
    run_path = ("tr_reports/0916_25.0.7_365_Ultra_Ultimate_VL/runs/"
                "20260917T023120950279Z_811ff47f")
    write_run(tmp_path, "0916_25.0.7_365_Ultra_Ultimate_VL",
              "20260917T023120950279Z_811ff47f", details={"products": {}})
    record = read_run_record(tmp_path / run_path)
    assert record["provenance"] == "directory"
    assert record["close_build"] == "0916_25.0.7_365_Ultra_Ultimate_VL"
    assert record["bug_count"] is None


def test_directories_that_are_not_runs_are_ignored(tmp_path):
    write_run(tmp_path, "16.8.0.189063", "20260917T191058045785Z_5064b828",
              header=report_header("16.8.0.189063", 26))
    (tmp_path / "tr_reports" / ".staging").mkdir(parents=True, exist_ok=True)
    (tmp_path / "tr_reports/16.8.0.189063/runs/scratch").mkdir()
    empty = tmp_path / "tr_reports/16.8.0.189063/runs/20260101T000000000000Z_deadbeef"
    empty.mkdir()
    assert read_run_record(tmp_path / "tr_reports/16.8.0.189063/runs/scratch") is None
    assert read_run_record(empty) is None     # a stamp alone is not a run
    assert len(run_history(tmp_path, days=3650, now=NOW)) == 1


def test_the_window_excludes_runs_older_than_the_requested_days(tmp_path):
    write_run(tmp_path, "16.8.0.189063", "20260917T191058045785Z_5064b828",
              header=report_header("16.8.0.189063", 26))
    write_run(tmp_path, "16.5.0.185409", "20260715T070000000000Z_aaaaaaaa",
              header=report_header("16.5.0.185409", 4))
    recent = run_history(tmp_path, days=10, now=NOW)
    assert [row["close_build"] for row in recent] == ["16.8.0.189063"]
    assert len(run_history(tmp_path, days=90, now=NOW)) == 2


def test_history_is_newest_first(tmp_path):
    for run_id, hour in (("20260916T082058073674Z_50de2f12", 8),
                         ("20260917T011200234546Z_ce9e6652", 1),
                         ("20260917T191058045785Z_5064b828", 19)):
        write_run(tmp_path, "16.8.0.189063", run_id,
                  header=report_header("16.8.0.189063", 26))
    hours = [row["run_at"].hour for row in run_history(tmp_path, days=10, now=NOW)]
    assert hours == [19, 1, 8]


def test_cohort_growth_is_measured_only_within_one_close_build(tmp_path):
    """26 bugs after 20 is a cohort that grew; after another build it is noise.

    Build 16.8.0.189063 held 20 bugs on the evening run and 26 the next
    morning as more bugs closed into it — a real change worth seeing. The 1
    bug of the preceding build is a different cohort entirely, so the two
    numbers must not be subtracted.
    """
    write_run(tmp_path, "16.7.5.188935", "20260915T010700916395Z_e0580375",
              header=report_header("16.7.5.188935", 1))
    write_run(tmp_path, "16.8.0.189063", "20260915T191109366419Z_24b16607",
              header=report_header("16.8.0.189063", 20))
    write_run(tmp_path, "16.8.0.189063", "20260916T082058073674Z_50de2f12",
              header=report_header("16.8.0.189063", 26))
    deltas = {
        row["run_id"][:8] + row["close_build"]: row["bug_delta"]
        for row in run_history(tmp_path, days=10, now=NOW)
    }
    assert deltas["2026091616.8.0.189063"] == 6
    assert deltas["2026091516.8.0.189063"] is None   # first run of this build
    assert deltas["2026091516.7.5.188935"] is None   # a different cohort


def test_the_run_the_page_is_showing_is_marked_once(tmp_path):
    run_path = "tr_reports/16.8.0.189063/runs/20260917T191058045785Z_5064b828"
    write_run(tmp_path, "16.8.0.189063", "20260917T191058045785Z_5064b828",
              header=report_header("16.8.0.189063", 26))
    write_run(tmp_path, "16.8.0.189063", "20260917T073933264868Z_0bdb8f14",
              header=report_header("16.8.0.189063", 26))
    manifest = {"report_path": f"{run_path}/test_focus_summary.md"}
    current = current_run_dir(tmp_path, manifest)
    rows = run_history(tmp_path, days=10, now=NOW, current_dir=current)
    assert [row["is_current"] for row in rows] == [True, False]


def test_a_manifest_path_outside_the_product_is_not_followed(tmp_path):
    assert current_run_dir(tmp_path, {"report_path": "../../etc/test_focus_summary.md"}) is None
    assert current_run_dir(tmp_path, {}) is None


def test_a_past_run_shows_the_focus_list_it_published(tmp_path):
    """The archived page and the archived file must not disagree.

    The live tab prefers the stored artifact for exactly this reason; reading
    history is no different.
    """
    run_path = "tr_reports/16.8.0.189063/runs/20260917T191058045785Z_5064b828"
    write_run(tmp_path, "16.8.0.189063", "20260917T191058045785Z_5064b828",
              header=report_header("16.8.0.189063", 26),
              focus_list="# What to test — build 16.8.0.189063\n",
              details=focus_details())
    markdown, note = run_focus_list(read_run_record(tmp_path / run_path))
    assert markdown.startswith("# What to test — build 16.8.0.189063")
    assert "published" in note


def test_a_run_from_before_the_focus_list_is_rebuilt_and_says_so(tmp_path):
    run_path = "tr_reports/16.8.0.189063/runs/20260915T191109366419Z_24b16607"
    write_run(tmp_path, "16.8.0.189063", "20260915T191109366419Z_24b16607",
              header=report_header("16.8.0.189063", 1), details=focus_details())
    markdown, note = run_focus_list(read_run_record(tmp_path / run_path))
    assert "What to test" in markdown and "A-TODO" in markdown
    assert "Rebuilt" in note and "predates" in note


def test_a_run_with_no_evidence_left_reports_that_instead_of_an_empty_list(tmp_path):
    run_path = "tr_reports/16.8.0.189063/runs/20260915T191109366419Z_24b16607"
