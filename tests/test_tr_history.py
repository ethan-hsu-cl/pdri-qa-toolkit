def test_digest_counts_days_with_runs_not_days_in_the_window(tmp_path):
    """Several runs a day is normal, and a quiet day publishes nothing.

    Runs-per-day would read as coverage; the honest summary is how many days
    actually produced a published run.
    """
    write_run(tmp_path, "16.8.0.189063", "20260917T011200234546Z_ce9e6652",
              header=report_header("16.8.0.189063", 26))
    write_run(tmp_path, "16.8.0.189063", "20260917T191058045785Z_5064b828",
              header=report_header("16.8.0.189063", 26))
    write_run(tmp_path, "16.7.5.188935", "20260914T190904776293Z_de7a2c74",
              header=report_header("16.7.5.188935", 1))
    digest = history_digest(run_history(tmp_path, days=10, now=NOW), 10)
    assert digest["run_count"] == 3
    assert digest["days_with_runs"] == 2
    assert digest["builds"] == ["16.8.0.189063", "16.7.5.188935"]


